# ---- where RStudio keeps themes ---------------------------------------------

local_theme_dirs <- function() {
  dirs <- character()
  f <- rs_internal(".rs.getThemeInstallDir")
  if (!is.null(f)) {
    dirs <- c(dirs, tryCatch(f(FALSE), error = function(e) character()))
  }
  cfg <- Sys.getenv("RSTUDIO_CONFIG_HOME")
  if (nzchar(cfg)) {
    dirs <- c(dirs, file.path(cfg, "themes"))
  }
  if (.Platform$OS.type == "windows") {
    appdata <- Sys.getenv("APPDATA")
    if (nzchar(appdata)) dirs <- c(dirs, file.path(appdata, "RStudio", "themes"))
  } else {
    xdg <- Sys.getenv("XDG_CONFIG_HOME")
    if (!nzchar(xdg)) xdg <- "~/.config"
    dirs <- c(dirs, file.path(xdg, "rstudio", "themes"))
  }
  dirs <- c(dirs, "~/.R/rstudio/themes")
  unique(normalizePath(dirs, winslash = "/", mustWork = FALSE))
}

global_theme_dirs <- function() {
  dirs <- if (.Platform$OS.type == "windows") {
    file.path(Sys.getenv("ProgramData"), "RStudio", "themes")
  } else {
    "/etc/rstudio/themes"
  }
  unique(normalizePath(dirs, winslash = "/", mustWork = FALSE))
}

builtin_theme_dirs <- function() {
  dirs <- getOption("rswallpaper.builtin_dir", character())
  postback <- Sys.getenv("RS_RPOSTBACK_PATH")
  if (nzchar(postback)) {
    dirs <- c(dirs, file.path(dirname(dirname(postback)), "resources", "themes"))
  }
  pandoc <- Sys.getenv("RSTUDIO_PANDOC")
  if (nzchar(pandoc)) {
    # .../app/quarto/bin/tools -> .../app/resources/themes
    d <- pandoc
    for (i in 1:6) {
      d <- dirname(d)
      dirs <- c(dirs, file.path(d, "resources", "themes"))
    }
  }
  dirs <- c(
    dirs,
    "/Applications/RStudio.app/Contents/Resources/app/resources/themes",
    "~/Applications/RStudio.app/Contents/Resources/app/resources/themes",
    "/usr/lib/rstudio/resources/app/resources/themes",
    "/usr/lib/rstudio/resources/themes",
    "/usr/lib/rstudio-server/resources/themes",
    file.path(Sys.getenv("ProgramFiles"), "RStudio", "resources", "app", "resources", "themes"),
    file.path(Sys.getenv("ProgramFiles"), "RStudio", "resources", "themes"),
    file.path(Sys.getenv("LOCALAPPDATA"), "Programs", "RStudio", "resources", "app", "resources", "themes")
  )
  dirs <- unique(normalizePath(dirs, winslash = "/", mustWork = FALSE))
  dirs <- dirs[dir.exists(dirs)]
  # The first existing install wins; different installs ship the same themes.
  utils::head(dirs, 1)
}

read_theme_header <- function(path) {
  head <- readLines(path, n = 12, warn = FALSE, encoding = "UTF-8")
  grab <- function(key) {
    m <- regmatches(head, regexec(paste0(key, "\\s*:\\s*([^*]+?)\\s*\\*/"), head, perl = TRUE))
    m <- Filter(length, m)
    if (length(m)) m[[1]][2] else NA_character_
  }
  name <- grab("rs-theme-name")
  if (is.na(name)) {
    name <- tools::file_path_sans_ext(basename(path))
  }
  list(
    name = name,
    is_dark = identical(toupper(grab("rs-theme-is-dark")), "TRUE"),
    base = grab("rswallpaper-base"),
    generated = !is.na(grab("rswallpaper-version"))
  )
}

scan_theme_dir <- function(dirs, source) {
  files <- unlist(lapply(dirs[dir.exists(dirs)], list.files,
                         pattern = "\\.rstheme$", full.names = TRUE, ignore.case = TRUE))
  if (!length(files)) {
    return(empty_theme_table())
  }
  info <- lapply(files, read_theme_header)
  data.frame(
    name = vapply(info, `[[`, "", "name"),
    is_dark = vapply(info, `[[`, NA, "is_dark"),
    source = source,
    wallpaper = vapply(info, `[[`, NA, "generated"),
    base = vapply(info, `[[`, "", "base"),
    path = normalizePath(files, winslash = "/"),
    stringsAsFactors = FALSE
  )
}

empty_theme_table <- function() {
  data.frame(name = character(), is_dark = logical(), source = character(),
             wallpaper = logical(), base = character(), path = character(),
             stringsAsFactors = FALSE)
}

#' List themes that can be used as a base
#'
#' Combines rswallpaper's preset palettes with the themes RStudio can see:
#' your installed custom themes (e.g. from \pkg{rsthemes} or
#' \pkg{rstudiothemes}), system-wide themes and the themes bundled with
#' RStudio. Any `name` returned here can be passed as `theme` to
#' [set_wallpaper()].
#'
#' @param source Which kinds of themes to include.
#' @return A data frame with columns `name`, `is_dark`, `source`,
#'   `wallpaper` (generated by rswallpaper?), `base` and `path`.
#' @export
#' @examples
#' head(list_themes())
list_themes <- function(source = c("palette", "installed", "global", "builtin")) {
  source <- match.arg(source, several.ok = TRUE)
  parts <- list()
  if ("palette" %in% source) {
    p <- palettes()
    parts$palette <- data.frame(
      name = p$name, is_dark = p$dark, source = "palette", wallpaper = FALSE,
      base = NA_character_, path = NA_character_, stringsAsFactors = FALSE
    )
  }
  if ("installed" %in% source) parts$installed <- scan_theme_dir(local_theme_dirs(), "installed")
  if ("global" %in% source) parts$global <- scan_theme_dir(global_theme_dirs(), "global")
  if ("builtin" %in% source) parts$builtin <- scan_theme_dir(builtin_theme_dirs(), "builtin")
  out <- do.call(rbind, c(list(empty_theme_table()), parts))
  # RStudio lets local themes shadow global and built-in ones of the same name.
  out <- out[!duplicated(tolower(out$name)), , drop = FALSE]
  rownames(out) <- NULL
  out
}

# ---- resolving the `theme` argument ----------------------------------------

# Returns list(label, is_dark, css, palette) where `css` has no header lines
# and no previous rswallpaper block.
resolve_theme <- function(theme = NULL, img = NULL, quiet = FALSE) {
  if (inherits(theme, "rsw_palette")) {
    return(palette_base(theme))
  }
  if (is.null(theme)) {
    if (!in_rstudio()) {
      stop("`theme` is required outside RStudio (e.g. theme = \"sakura\" or an installed theme name).",
           call. = FALSE)
    }
    theme <- rstudioapi::getThemeInfo()$editor
  }
  check_string(theme, "theme")

  key <- tolower(theme)
  if (key %in% c("auto", "auto-dark")) {
    if (is.null(img)) {
      stop("`theme = \"", theme, "\"` needs an image to take colours from.", call. = FALSE)
    }
    return(palette_base(palette_from_image(img, dark = key == "auto-dark")))
  }
  if (!is.null(preset_palette(key))) {
    return(palette_base(preset_palette(key)))
  }
  if (file.exists(theme) && !dir.exists(theme)) {
    return(file_base(theme, quiet))
  }

  known <- list_themes(c("installed", "global", "builtin"))
  hit <- known[tolower(known$name) == key, , drop = FALSE]
  if (!nrow(hit)) {
    close <- c(palettes()$name, known$name)
    close <- close[agrepl(theme, close, ignore.case = TRUE, max.distance = 0.2)]
    stop("Theme \"", theme, "\" not found.",
         if (length(close)) paste0(" Did you mean: ", paste0("\"", utils::head(close, 5), "\"", collapse = ", "), "?"),
         " See list_themes().", call. = FALSE)
  }
  hit <- hit[1, ]
  # A wallpaper theme used as base: go back to what it was built from.
  if (isTRUE(hit$wallpaper) && !is.na(hit$base) && !identical(tolower(hit$base), key)) {
    return(tryCatch(resolve_theme(hit$base, quiet = quiet), error = function(e) file_base(hit$path, quiet)))
  }
  file_base(hit$path, quiet)
}

palette_base <- function(p) {
  list(label = p$name, is_dark = p$dark, css = palette_css(p), palette = p)
}

file_base <- function(path, quiet = FALSE) {
  if (grepl("\\.tmtheme$", path, ignore.case = TRUE)) {
    require_rstudio("Converting a .tmTheme")
    out <- tempfile("rsw-tm")
    dir.create(out)
    rstudioapi::convertTheme(path, add = FALSE, outputLocation = out)
    path <- list.files(out, pattern = "\\.rstheme$", full.names = TRUE)[1]
  }
  header <- read_theme_header(path)
  css <- strip_theme(readLines(path, warn = FALSE, encoding = "UTF-8"))
  legacy <- strip_legacy_wallpaper(css)
  if (legacy$removed > 0) {
    css <- legacy$css
    if (!quiet) {
      message("Removed the image built into \"", header$name, "\" so it is not stacked under the new wallpaper.")
    }
  }
  list(label = if (!is.na(header$base)) header$base else header$name,
       is_dark = header$is_dark, css = css, palette = NULL)
}

# Drops hand-made wallpapers (e.g. from a script or another tool): rules whose
# ::before/::after pseudo-element paints an image. Indent-guide data URIs and
# the terminal cursor's ::before are left alone. Returns list(css, removed).
strip_legacy_wallpaper <- function(css) {
  if (!any(grepl("url(", css, fixed = TRUE))) {
    return(list(css = css, removed = 0L))
  }
  txt <- paste(css, collapse = "\n")
  m <- gregexpr("[^{}]+\\{[^{}]*\\}", txt, perl = TRUE)[[1]]
  if (m[1] == -1) {
    return(list(css = css, removed = 0L))
  }
  starts <- as.integer(m)
  lens <- attr(m, "match.length")
  blocks <- substring(txt, starts, starts + lens - 1)
  selectors <- sub("(?s)\\{.*$", "", gsub("(?s)/\\*.*?\\*/", "", blocks, perl = TRUE), perl = TRUE)
  bodies <- sub("(?s)^[^{]*\\{", "", blocks, perl = TRUE)
  drop <- which(grepl("::?(after|before)", selectors) & grepl("url\\(", bodies))
  for (i in rev(drop)) {
    txt <- paste0(substr(txt, 1, starts[i] - 1), substr(txt, starts[i] + lens[i], nchar(txt)))
  }
  list(css = strsplit(txt, "\n", fixed = TRUE)[[1]], removed = length(drop))
}

strip_theme <- function(css) {
  begin <- which(css == MARK_BEGIN)
  end <- which(css == MARK_END)
  if (length(begin) && length(end)) {
    drop <- unlist(Map(seq, begin, vapply(begin, function(b) min(c(end[end > b], length(css))), 1)))
    css <- css[-drop]
  }
  header <- grepl("^\\s*/\\*\\s*(rs-theme-name|rs-theme-is-dark|rswallpaper-[a-z]+)\\s*:.*\\*/\\s*$", css)
  css[!header]
}
